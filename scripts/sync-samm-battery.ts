/**
 * Sync the SAMM-generated JSON Schemas and example payloads of two battery passport models into
 * vendor/<model>/<version>/:
 *   - Battery Pass Consortium data model 1.2 (github.com/batterypass/BatteryPassDataModel,
 *     CC BY 4.0): one aspect per data group, each at its newest version (Performance 1.2.1, the
 *     others 1.2.0), aligned with DIN DKE SPEC 99100:2025.
 *   - Catena-X battery_pass 6.1.0 (github.com/eclipse-tractusx/sldt-semantic-models, CC BY 4.0).
 *
 *   pnpm run sync:samm-battery
 *
 * NETWORK SYNC — NEVER RUN THIS AS PART OF A BULK REGENERATION. Sync on purpose, in its own
 * commit, and read the diff (see the note in sync-cirpass2.ts).
 *
 * The files are written byte for byte; some of the consortium's are UTF-16 with a byte-order mark,
 * which scripts/lib/targets.ts reads as such. Both repositories are pinned by commit.
 */
import { createHash } from "node:crypto";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");

interface Source {
  out: string;
  title: string;
  version: string;
  repository: string;
  commit: string;
  /** Upstream path → local path. */
  files: Record<string, string>;
}

const BPC = "BatteryPass/io.BatteryPass.";
const SOURCES: Source[] = [
  {
    out: "vendor/batterypass-samm/1.2",
    title: "Battery Pass Consortium data model (SAMM), generated JSON Schemas and payloads",
    version: "1.2",
    repository: "https://github.com/batterypass/BatteryPassDataModel",
    commit: "7f40918",
    files: {
      [`${BPC}CarbonFootprint/1.2.0/gen/CarbonFootprintForBatteries-schema.json`]: "carbon-footprint/schema.json",
      [`${BPC}CarbonFootprint/1.2.0/gen/CarbonFootprintForBatteries-payload.json`]: "carbon-footprint/payload.json",
      [`${BPC}Circularity/1.2.0/gen/Circularity-schema.json`]: "circularity/schema.json",
      [`${BPC}Circularity/1.2.0/gen/Circularity.json`]: "circularity/payload.json",
      [`${BPC}GeneralProductInformation/1.2.0/gen/GeneralProductInformation-schema.json`]: "general-product-information/schema.json",
      [`${BPC}GeneralProductInformation/1.2.0/gen/GeneralProductInformation-payload.json`]: "general-product-information/payload.json",
      [`${BPC}Labels/1.2.0/gen/Labeling-schema.json`]: "labels/schema.json",
      [`${BPC}Labels/1.2.0/gen/Labeling-payload.json`]: "labels/payload.json",
      [`${BPC}MaterialComposition/1.2.0/gen/MaterialComposition-schema.json`]: "material-composition/schema.json",
      [`${BPC}MaterialComposition/1.2.0/gen/MaterialComposition-payload.json`]: "material-composition/payload.json",
      [`${BPC}Performance/1.2.1/gen/PerformanceAndDurability.schema`]: "performance/schema.json",
      [`${BPC}Performance/1.2.1/gen/PerformanceAndDurability.json`]: "performance/payload.json",
      [`${BPC}SupplyChainDueDiligence/1.2.0/gen/SupplyChainDueDiligence-schema.json`]: "supply-chain-due-diligence/schema.json",
      [`${BPC}SupplyChainDueDiligence/1.2.0/gen/SupplyChainDueDiligence-payload.json`]: "supply-chain-due-diligence/payload.json",
      ["README.md"]: "README.upstream.md",
    },
  },
  {
    out: "vendor/catenax-battery-pass/6.1.0",
    title: "Catena-X battery pass aspect model (SAMM), generated JSON Schema and payload",
    version: "6.1.0",
    repository: "https://github.com/eclipse-tractusx/sldt-semantic-models",
    commit: "46b4def77a831559bedc402dcafeb17f119b8f17",
    files: {
      "io.catenax.battery.battery_pass/6.1.0/gen/BatteryPass-schema.json": "schema.json",
      "io.catenax.battery.battery_pass/6.1.0/gen/BatteryPass.json": "payload.json",
      "io.catenax.battery.battery_pass/6.1.0/metadata.json": "metadata.json",
      "io.catenax.battery.battery_pass/RELEASE_NOTES.md": "RELEASE_NOTES.md",
    },
  },
];

for (const s of SOURCES) {
  const repo = s.repository.replace("https://github.com/", "");
  const commit = ((await (await fetch(`https://api.github.com/repos/${repo}/commits/${s.commit}`)).json()) as { sha: string }).sha;
  const manifest: { path: string; upstream: string; sha256: string }[] = [];
  for (const [upstream, local] of Object.entries(s.files)) {
    const res = await fetch(`https://raw.githubusercontent.com/${repo}/${commit}/${encodeURI(upstream)}`);
    if (!res.ok) throw new Error(`${upstream}: HTTP ${res.status}`);
    const bytes = Buffer.from(await res.arrayBuffer());
    mkdirSync(dirname(join(ROOT, s.out, local)), { recursive: true });
    writeFileSync(join(ROOT, s.out, local), bytes);
    manifest.push({ path: local, upstream, sha256: createHash("sha256").update(bytes).digest("hex") });
  }
  writeFileSync(join(ROOT, s.out, "MANIFEST.json"), JSON.stringify({
    $comment: "GENERATED by scripts/sync-samm-battery.ts - do not edit.",
    title: s.title,
    version: s.version,
    commit,
    retrieved: new Date().toISOString().slice(0, 10),
    repository: s.repository,
    license: "https://creativecommons.org/licenses/by/4.0/",
    files: manifest.sort((a, b) => a.path.localeCompare(b.path)),
  }, null, 2) + "\n");
  console.log(`${s.out}: ${manifest.length} files (${repo}@${commit.slice(0, 8)})`);
}
