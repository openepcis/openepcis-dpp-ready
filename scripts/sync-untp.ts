/**
 * Sync the UN Transparency Protocol (UNTP) JSON Schemas and sample credentials into
 * vendor/untp/<version>/.
 *
 *   pnpm run sync:untp -- --version 0.8.0
 *   pnpm run sync:untp -- --latest          # the newest version untp.unece.org publishes artefacts for
 *
 * NETWORK SYNC — NEVER RUN THIS AS PART OF A BULK REGENERATION. Sync on purpose, in its own
 * commit, and read the diff (see the note in sync-cirpass2.ts).
 *
 * SOURCE. UNTP (UN/CEFACT, CC BY 4.0) publishes one JSON Schema per credential and a sample
 * instance under https://untp.unece.org/artefacts/{schema,samples}/v<version>/<credential>/. The
 * schemas are self-contained (no external $ref). A version is a validation target of its own
 * (extensions/common/interop/targets/untp/<version>); an older one stays until removed on purpose.
 * --latest probes versions upward and takes the newest whose product passport schema answers 200.
 *
 * OUTPUT.
 *   vendor/untp/<version>/{schema,samples}/<credential>/<Name>[_instance].json   verbatim
 *   vendor/untp/<version>/MANIFEST.json   source, retrieval date, licence, per-file SHA-256
 */
import { createHash } from "node:crypto";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const BASE = "https://untp.unece.org/artefacts/";
const CREDENTIALS = [
  ["dpp", "DigitalProductPassport"],
  ["dcc", "ConformityCredential"],
  ["dfr", "DigitalFacilityRecord"],
  ["dia", "DigitalIdentityAnchor"],
  ["dte", "DigitalTraceabilityEvent"],
] as const;

const ok = async (url: string) => (await fetch(url, { method: "HEAD" })).status === 200;

async function latest(): Promise<string> {
  let best: string | undefined;
  for (let major = 0; major <= 2; major++) {
    for (let minor = 0; minor <= 20; minor++) {
      let found = false;
      for (let patch = 0; patch <= 5; patch++) {
        const v = `${major}.${minor}.${patch}`;
        if (await ok(`${BASE}schema/v${v}/dpp/DigitalProductPassport.json`)) {
          best = v;
          found = true;
        }
      }
      if (!found && best && minor > Number(best.split(".")[1]) + 1) break;
    }
  }
  if (!best) throw new Error("no UNTP version with published artefacts found");
  return best;
}

const args = process.argv.slice(2);
const flag = args.indexOf("--version");
const version = flag >= 0 ? args[flag + 1] : args.includes("--latest") ? await latest() : undefined;
if (!version) {
  console.error("usage: sync-untp.ts --version <x.y.z> | --latest");
  process.exit(2);
}

const out = join(ROOT, "vendor/untp", version);
const manifest: { path: string; sha256: string }[] = [];
const missing: string[] = [];
for (const [dir, name] of CREDENTIALS) {
  for (const path of [`schema/${dir}/${name}.json`, `samples/${dir}/${name}_instance.json`]) {
    const res = await fetch(`${BASE}${path.replace(/^(schema|samples)\//, `$1/v${version}/`)}`);
    if (res.status === 404) {
      missing.push(path);
      continue;
    }
    if (!res.ok) throw new Error(`${path}: HTTP ${res.status}`);
    const bytes = Buffer.from(await res.arrayBuffer());
    JSON.parse(bytes.toString("utf8"));
    mkdirSync(dirname(join(out, path)), { recursive: true });
    writeFileSync(join(out, path), bytes);
    manifest.push({ path, sha256: createHash("sha256").update(bytes).digest("hex") });
  }
}
writeFileSync(join(out, "MANIFEST.json"), JSON.stringify({
  $comment: "GENERATED by scripts/sync-untp.ts - do not edit.",
  title: "UN Transparency Protocol, JSON Schemas and samples",
  version,
  retrieved: new Date().toISOString().slice(0, 10),
  source: `${BASE}schema/v${version}/`,
  license: "https://creativecommons.org/licenses/by/4.0/",
  notPublished: missing,
  files: manifest.sort((a, b) => a.path.localeCompare(b.path)),
}, null, 2) + "\n");
console.log(`vendor/untp/${version}: ${manifest.length} files${missing.length ? `; not published: ${missing.join(", ")}` : ""}`);
