/**
 * Sync the GS1 EPCIS / CBV 2.0.1 validation artefacts and example documents into
 * vendor/gs1-epcis/2.0.1/.
 *
 *   pnpm run sync:epcis
 *
 * NETWORK SYNC — NEVER RUN THIS AS PART OF A BULK REGENERATION. Sync on purpose, in its own
 * commit, and read the diff (see the note in sync-cirpass2.ts).
 *
 * SOURCE. The artefacts GS1 publishes for the standard on ref.gs1.org/standards/epcis/2.0.1/ (JSON
 * Schema, SHACL shapes, the EPCIS and CBV ontologies, the JSON-LD context), plus the JSON Schema of
 * 2.0.0, which UNTP's traceability event names by its $id. The example documents come from the
 * standard's repository (github.com/gs1/EPCIS, JSON/), pinned by commit; an example that is not a
 * plain-JSON EPCISDocument (a query document, one with comments) is left out. Licence: GS1 IP
 * policy; this project treats the artefacts as freely redistributable, like Apache 2.0 (decision of
 * 2026-11-12, recorded in vendor/gs1-epcis/README.md).
 *
 * OUTPUT.
 *   vendor/gs1-epcis/2.0.1/<file>                 verbatim, from ref.gs1.org
 *   vendor/gs1-epcis/2.0.1/2.0.0/<file>           the 2.0.0 JSON Schema
 *   vendor/gs1-epcis/2.0.1/examples/<path>        verbatim, from the repository
 *   vendor/gs1-epcis/2.0.1/MANIFEST.json          commit, retrieval date, licence, per-file SHA-256
 */
import { createHash } from "node:crypto";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const REF = "https://ref.gs1.org/standards/epcis/";
const REPOSITORY = "https://github.com/gs1/EPCIS";
const COMMIT = "6f71468231838e424bb5dfa836e006e8dc69615c";
const VERSION = "2.0.1";

const published: [string, string][] = [
  ["epcis-json-schema.json", `${VERSION}/epcis-json-schema.json`],
  ["epcis-shacl.ttl", `${VERSION}/epcis-shacl.ttl`],
  ["epcis-ontology.ttl", `${VERSION}/epcis-ontology.ttl`],
  ["cbv-ontology.ttl", `${VERSION}/cbv-ontology.ttl`],
  ["epcis-context.jsonld", `${VERSION}/epcis-context.jsonld`],
  ["2.0.0/epcis-json-schema.json", "2.0.0/epcis-json-schema.json"],
];

const tree = (await (await fetch(`https://api.github.com/repos/gs1/EPCIS/git/trees/${COMMIT}?recursive=1`)).json()) as { tree: { path: string; type: string }[] };
const examples = tree.tree.filter((e) => e.type === "blob" && /^JSON\/.*\.jsonld$/.test(e.path)).map((e) => e.path).sort();

const out = join(ROOT, "vendor/gs1-epcis", VERSION);
const manifest: { path: string; sha256: string }[] = [];
const skipped: string[] = [];
const put = (path: string, bytes: Buffer) => {
  mkdirSync(dirname(join(out, path)), { recursive: true });
  writeFileSync(join(out, path), bytes);
  manifest.push({ path, sha256: createHash("sha256").update(bytes).digest("hex") });
};
for (const [local, remote] of published) {
  const res = await fetch(REF + remote, { redirect: "follow" });
  if (!res.ok) throw new Error(`${remote}: HTTP ${res.status}`);
  put(local, Buffer.from(await res.arrayBuffer()));
}
for (const path of examples) {
  const res = await fetch(`https://raw.githubusercontent.com/gs1/EPCIS/${COMMIT}/${encodeURI(path)}`);
  if (!res.ok) throw new Error(`${path}: HTTP ${res.status}`);
  const bytes = Buffer.from(await res.arrayBuffer());
  let doc: { type?: string } | undefined;
  try {
    doc = JSON.parse(bytes.toString("utf8"));
  } catch {
    skipped.push(`${path} (not plain JSON)`);
    continue;
  }
  if (doc?.type !== "EPCISDocument") {
    skipped.push(`${path} (type ${doc?.type})`);
    continue;
  }
  put(`examples/${path.replace(/^JSON\//, "")}`, bytes);
}
writeFileSync(join(out, "MANIFEST.json"), JSON.stringify({
  $comment: "GENERATED by scripts/sync-epcis.ts - do not edit.",
  title: "GS1 EPCIS / CBV, validation artefacts and examples",
  version: VERSION,
  commit: COMMIT,
  retrieved: new Date().toISOString().slice(0, 10),
  repository: REPOSITORY,
  source: `${REF}${VERSION}/`,
  license: "https://www.gs1.org/standards/ip (treated as freely redistributable, see vendor/gs1-epcis/README.md)",
  skipped,
  files: manifest.sort((a, b) => a.path.localeCompare(b.path)),
}, null, 2) + "\n");
console.log(`vendor/gs1-epcis/${VERSION}: ${manifest.length} files; left out: ${skipped.length}`);
for (const s of skipped) console.log(`  ${s}`);
