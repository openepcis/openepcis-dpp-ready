#!/usr/bin/env tsx
/**
 * Generate one GITB TDL test suite per external target and version: the artifact a third party
 * runs on an Interoperability Test Bed to obtain a conformance statement against that release of
 * the external model (EU DPP Registry 1.0.0, BatteryPass-Ready 2.0.1, …), with the validation
 * types OpenEPCIS DPP-Ready hosts for it (scripts/lib/targets.ts, scripts/build-gitb-resources.ts).
 *
 * Output (all generated — do not hand-edit):
 *   gitb/test-suites/interop-<target>-<version>/testSuite.xml
 *   gitb/test-suites/interop-<target>-<version>/testCases/tc-*.xml
 *   gitb/test-suites/interop-<target>-<version>/resources/{json,rdf}/…
 *
 * Per validation type:
 *   tc-upload-json-<type>  the system under test uploads its document; JSON validator.
 *   tc-upload-rdf-<type>   the same document as RDF (Turtle, JSON-LD, N-Quads); SHACL validator.
 *   tc-selftest-<type>     no interaction: every example the publisher ships for the type must
 *                          pass, a document that is not one must be rejected (invert).
 *   tc-bridge-<type>       no interaction: what OpenEPCIS DPP-Ready's crosswalk produces for the
 *                          type and the hosted type accepts (the bridge's own conformance; the
 *                          rest, with reasons, is docs/conformance/INTEROP_CONFORMANCE.md).
 * RDF fixtures are the documents as the crosswalk profile reads them, pre-expanded to N-Quads:
 * the publisher's contexts do not resolve (EU DPP Registry: no DNS) or do not exist (BatteryPass-
 * Ready), so the upload of JSON with an @context is not something the hosted validator can do.
 *
 * Usage:
 *   tsx scripts/build-gitb-interop-testsuites.ts [--write]
 *   SHACL_VALIDATOR_ADDRESS=… JSON_VALIDATOR_ADDRESS=… tsx scripts/build-gitb-interop-testsuites.ts --write
 */
import { promises as fs } from "node:fs";
import path from "node:path";
import { Writer } from "n3";
import { VALIDATOR_DOMAIN } from "./lib/gitb.ts";
import { ROOT } from "./lib/modules.ts";
import { GARBAGE, documentQuads, fixturesOf, livenessMutation, loadTargets, provenance, readDocument, rootType, verdict, TURTLE, type Target, type TargetType } from "./lib/targets.ts";

const WRITE = process.argv.includes("--write");
const SUITES = path.join(ROOT, "gitb/test-suites");
const SHACL_WSDL = `${process.env.SHACL_VALIDATOR_ADDRESS ?? "http://shacl-validator:8080"}/shacl/soap/${VALIDATOR_DOMAIN}/validation?wsdl`;
const JSON_WSDL = `${process.env.JSON_VALIDATOR_ADDRESS ?? "http://json-validator:8080"}/json/soap/${VALIDATOR_DOMAIN}/validation?wsdl`;
const ACTOR = "DPPDataProvider";
const PROBE_NQ = `<urn:openepcis:probe> <urn:openepcis:says> "not a passport" .\n`;

const xml = (s: string) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const slug = (file: string) =>
  file.replace(/^(vendor|extensions\/common\/interop\/crosswalk|extensions\/eu\/battery\/examples)\//, "").replace(/\.json$/, "").replace(/[^A-Za-z0-9.-]+/g, "_");

interface Step {
  name: string;
  resource: string;
  label: string;
  kind: "json" | "rdf";
  invert?: boolean;
}

const header = `<!-- GENERATED by scripts/build-gitb-interop-testsuites.ts (pnpm run build:gitb-testsuite) — do not edit. -->`;

function verifyStep(id: string, s: Step, type: string): string {
  const rdf = s.kind === "rdf";
  return `    <verify id="${id}" handler="${xml(rdf ? SHACL_WSDL : JSON_WSDL)}"${s.invert ? ` invert="true"` : ""}
            desc="${xml(s.label)}">
      <input name="contentToValidate">$${s.name}</input>
      <input name="validationType">"${xml(type)}"</input>
      <input name="embeddingMethod">"BASE64"</input>${rdf ? `\n      <input name="contentSyntax">"application/n-quads"</input>` : ""}
    </verify>`;
}

function automaticCase(id: string, name: string, description: string, steps: Step[], ok: string, ko: string, version: string): string {
  return `<?xml version="1.0" encoding="UTF-8"?>
${header}
<testcase id="${id}" xmlns="http://www.gitb.com/tdl/v1/" xmlns:gitb="http://www.gitb.com/core/v1/">
  <metadata>
    <gitb:name>${xml(name)}</gitb:name>
    <gitb:version>${xml(version)}</gitb:version>
    <gitb:description>${xml(description)}</gitb:description>
  </metadata>
  <actors>
    <gitb:actor id="${ACTOR}" name="Digital Product Passport data provider" role="SUT"/>
  </actors>
  <imports>
${steps.map((s) => `    <artifact type="binary" encoding="UTF-8" name="${s.name}">${s.resource}</artifact>`).join("\n")}
  </imports>
  <steps>
${steps.map((s, i) => verifyStep(`v${i}`, s, id.replace(/^tc-(selftest|bridge)-/, ""))).join("\n")}
  </steps>
  <output>
    <success><default>"${xml(ok)}"</default></success>
    <failure><default>"${xml(ko)}"</default></failure>
  </output>
</testcase>
`;
}

function uploadCase(t: Target, type: TargetType, kind: "json" | "rdf", version: string): string {
  const rdf = kind === "rdf";
  const what = rdf ? "the document as RDF (Turtle, N-Quads or JSON-LD whose @context resolves)" : "the document as JSON";
  return `<?xml version="1.0" encoding="UTF-8"?>
${header}
<testcase id="tc-upload-${kind}-${type.id}" xmlns="http://www.gitb.com/tdl/v1/" xmlns:gitb="http://www.gitb.com/core/v1/">
  <metadata>
    <gitb:name>${xml(`[${type.id}] Validate an uploaded ${t.title} ${t.version} document (${rdf ? "SHACL" : "JSON Schema"})`)}</gitb:name>
    <gitb:version>${xml(version)}</gitb:version>
    <gitb:description>${xml(`Upload ${what} and validate it against ${type.label}, with the publisher's ${rdf ? "SHACL shapes" : "JSON Schemas"} of release ${t.version} as bundled from ${provenance(t)}.`)}</gitb:description>
  </metadata>
  <actors>
    <gitb:actor id="${ACTOR}" name="Digital Product Passport data provider" role="SUT"/>
  </actors>
  <steps>
    <interact id="userData" desc="Upload the document">
      <request desc="${xml(rdf ? "Document (RDF):" : "Document (JSON):")}" name="document" inputType="UPLOAD" required="true"/>
    </interact>
    <verify id="check" handler="${xml(rdf ? SHACL_WSDL : JSON_WSDL)}" desc="${xml(`Validate against ${type.id}`)}">
      <input name="contentToValidate">$userData{document}</input>
      <input name="validationType">"${xml(type.id)}"</input>
      <input name="embeddingMethod">"BASE64"</input>${rdf ? `\n      <input name="contentSyntax">"text/turtle"</input>` : ""}
    </verify>
  </steps>
  <output>
    <success><default>"${xml(`The document conforms to ${t.title} ${t.version} (${type.id}).`)}"</default></success>
    <failure><default>"${xml(`The document does not conform to ${t.title} ${t.version} (${type.id}). The failed step's report lists every finding.`)}"</default></failure>
  </output>
</testcase>
`;
}

async function suiteFiles(t: Target, version: string): Promise<{ files: Map<string, string>; cases: string[]; counts: string[] }> {
  const files = new Map<string, string>();
  const cases: string[] = [];
  const counts: string[] = [];
  const fixtures = fixturesOf(t);
  const nq = (q: Awaited<ReturnType<typeof documentQuads>>) => new Writer({ format: "application/n-quads" }).quadsToString(q);
  files.set("resources/json/not-a-passport.json", JSON.stringify(GARBAGE) + "\n");
  files.set("resources/rdf/not-a-passport.nq", PROBE_NQ);

  for (const type of t.types) {
    const self: Step[] = [];
    const bridge: Step[] = [];
    for (const f of fixtures.filter((x) => x.types.includes(type.id))) {
      const doc = readDocument(f.file);
      if (f.role !== "publisher" && !(await verdict(t, type, doc, { noShacl: !!f.noShacl })).valid) continue;
      const bad = f.expect === "invalid";
      const into = f.role === "publisher" ? self : bridge;
      const who = f.role === "publisher" ? `${t.publisher} ${bad ? "test case" : "example"}` : "OpenEPCIS DPP-Ready crosswalk output";
      const must = bad ? "must be REJECTED, as the publisher's corpus expects" : "must conform";
      if (type.schemas.length && !(TURTLE in doc)) {
        const res = `resources/json/${slug(f.file)}.json`;
        files.set(res, await fs.readFile(path.join(ROOT, f.file), "utf8"));
        into.push({ name: `j${into.length}`, resource: res, kind: "json", invert: bad, label: `${who} ${must} (JSON Schema): ${f.file}` });
      }
      if (type.shapes.length && !f.noShacl) {
        const res = `resources/rdf/${slug(f.file)}.nq`;
        files.set(res, nq(await documentQuads(t, doc)));
        into.push({ name: `r${into.length}`, resource: res, kind: "rdf", invert: bad, label: `${who} ${must} (SHACL): ${f.file}` });
      }
    }
    if (type.schemas.length) self.push({ name: `gj`, resource: "resources/json/not-a-passport.json", kind: "json", invert: true, label: "A document that is not one must be REJECTED (JSON Schema)" });
    if (type.shapes.length && rootType(t)) self.push({ name: `gr`, resource: "resources/rdf/not-a-passport.nq", kind: "rdf", invert: true, label: "A graph without the root class must be REJECTED (SHACL)" });
    const first = fixtures.find((x) => x.role === "publisher" && x.expect === "valid" && !x.noShacl && x.types.includes(type.id));
    if (type.shapes.length && first) {
      const m = await livenessMutation(t, type, await documentQuads(t, readDocument(first.file)));
      if (m) {
        const res = `resources/rdf/${type.id}.liveness.nq`;
        files.set(res, nq(m.quads));
        self.push({ name: `lr`, resource: res, kind: "rdf", invert: true, label: `The publisher's example with ${m.path.replace(/.*[#/]/, "")} retyped or dropped must be REJECTED (the publisher's shapes are live)` });
      }
    }

    for (const kind of ["json", "rdf"] as const) {
      if (kind === "json" ? !type.schemas.length : !type.shapes.length) continue;
      files.set(`testCases/tc-upload-${kind}-${type.id}.xml`, uploadCase(t, type, kind, version));
      cases.push(`tc-upload-${kind}-${type.id}`);
    }
    files.set(
      `testCases/tc-selftest-${type.id}.xml`,
      automaticCase(
        `tc-selftest-${type.id}`,
        `[${type.id}] Self-test: the publisher's examples pass, a non-document is rejected`,
        `Runs without interaction. Every example ${t.publisher} ships for ${type.label} must conform, and a document that is not one must not; together they prove the hosted type discriminates and is faithful to the release.`,
        self,
        `The ${type.id} type accepts the publisher's examples and rejects a non-document.`,
        `Self-test failed: the hosted ${type.id} type does not say what release ${t.version} says.`,
        version,
      ),
    );
    cases.push(`tc-selftest-${type.id}`);
    if (bridge.length) {
      files.set(
        `testCases/tc-bridge-${type.id}.xml`,
        automaticCase(
          `tc-bridge-${type.id}`,
          `[${type.id}] Bridge: OpenEPCIS DPP-Ready output conforms`,
          `Runs without interaction. Documents the OpenEPCIS DPP-Ready crosswalk (profile ${t.profile ?? "none"}) produces for ${type.label}, validated by the hosted type. The full statement, incomplete documents and accepted deviations included, is docs/conformance/INTEROP_CONFORMANCE.md of the same release.`,
          bridge,
          `OpenEPCIS DPP-Ready output conforms to ${type.id}.`,
          `OpenEPCIS DPP-Ready output does not conform to ${type.id}.`,
          version,
        ),
      );
      cases.push(`tc-bridge-${type.id}`);
    }
    counts.push(`  ${type.id.padEnd(46)} ${self.filter((x) => !x.invert).length} publisher step(s), ${self.filter((x) => x.invert).length} negative, ${bridge.length} bridge step(s)`);
  }

  files.set(
    "testSuite.xml",
    `<?xml version="1.0" encoding="UTF-8"?>
${header}
<testsuite id="interop-${t.id}-${t.version}" xmlns="http://www.gitb.com/tdl/v1/" xmlns:gitb="http://www.gitb.com/core/v1/">
  <metadata>
    <gitb:name>${xml(`${t.title} ${t.version} conformance (hosted by OpenEPCIS DPP-Ready)`)}</gitb:name>
    <gitb:version>${xml(version)}</gitb:version>
    <gitb:description>${xml(`Conformance to ${provenance(t)}, with the publisher's artifacts bundled byte for byte by OpenEPCIS DPP-Ready ${version}. Hosting does not imply endorsement by the publisher. Upload cases for the system under test, self-tests that prove the hosted types are faithful to the release, and bridge cases for what OpenEPCIS DPP-Ready's crosswalk produces.`)}</gitb:description>
  </metadata>
  <actors>
    <gitb:actor id="${ACTOR}">
      <gitb:name>Digital Product Passport data provider</gitb:name>
      <gitb:desc>The economic operator or solution provider whose document is under test.</gitb:desc>
    </gitb:actor>
  </actors>
${cases.map((c) => `    <testcase id="${c}"/>`).join("\n")}
</testsuite>
`,
  );
  return { files, cases, counts };
}

async function reconcile(dir: string, files: Map<string, string>): Promise<string[]> {
  const changed: string[] = [];
  for (const [rel, content] of [...files].sort(([a], [b]) => a.localeCompare(b))) {
    const abs = path.join(dir, rel);
    const existing = await fs.readFile(abs, "utf8").catch(() => undefined);
    if (existing === content) continue;
    changed.push(path.relative(ROOT, abs));
    if (WRITE) {
      await fs.mkdir(path.dirname(abs), { recursive: true });
      await fs.writeFile(abs, content);
    }
  }
  const expected = new Set([...files.keys()].map((r) => path.join(dir, r)));
  for (const rel of await fs.readdir(dir, { recursive: true }).catch(() => [] as string[])) {
    const abs = path.join(dir, String(rel));
    if ((await fs.stat(abs)).isDirectory() || expected.has(abs)) continue;
    changed.push(`${path.relative(ROOT, abs)} (stale)`);
    if (WRITE) await fs.rm(abs);
  }
  return changed;
}

async function main() {
  const version = JSON.parse(await fs.readFile(path.join(ROOT, "package.json"), "utf8")).version as string;
  const changed: string[] = [];
  const live = new Set<string>();
  for (const t of loadTargets()) {
    const name = `interop-${t.id}-${t.version}`;
    live.add(name);
    const { files, cases, counts } = await suiteFiles(t, version);
    changed.push(...(await reconcile(path.join(SUITES, name), files)));
    console.log(`GITB interop suite ${name}: ${cases.length} test case(s)`);
    for (const c of counts) console.log(c);
  }
  // A suite of a target (version) that is gone would keep being offered.
  for (const name of await fs.readdir(SUITES)) {
    if (!name.startsWith("interop-") || live.has(name)) continue;
    changed.push(`gitb/test-suites/${name} (stale)`);
    if (WRITE) await fs.rm(path.join(SUITES, name), { recursive: true });
  }
  console.log(`\nValidator addresses baked into the suites: ${SHACL_WSDL}, ${JSON_WSDL}`);
  if (!changed.length) return console.log(`✓ committed interop test suites are in step with the targets.`);
  if (WRITE) return console.log(`✓ wrote ${changed.length} file(s).`);
  console.log(`\n✗ the committed interop test suites have drifted:`);
  for (const c of changed) console.log(`    ${c}`);
  console.log(`\nRegenerate with: pnpm run build:gitb-testsuite`);
  process.exit(1);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
