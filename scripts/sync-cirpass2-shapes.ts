/**
 * Sync the CIRPASS-2 SHACL shapes, the ontology modules they are evaluated with, and the
 * publisher's examples and test corpus into vendor/cirpass2-<module>/<version>/.
 *
 *   pnpm run sync:cirpass2-shapes
 *
 * NETWORK SYNC — NEVER RUN THIS AS PART OF A BULK REGENERATION. Sync on purpose, in its own
 * commit, and read the diff (see the note in sync-cirpass2.ts).
 *
 * SOURCE. Two CIRPASS-2 releases that ship shapes (CORE ships none):
 *   - Textile 2.0.0, the publication package of github.com/CIRPASS-2/ontologies-docs
 *     (Textile/2.0.0/package; CC BY 4.0, package LICENSE.md): shapes, ontology modules, the MIREOT
 *     extracts they depend on, examples and the SHACL test corpus with its expectations.
 *   - Battery shapes 0.3.0 / ontology 0.4.0, DRAFT, github.com/CIRPASS-2/ontologies-battery
 *     (Apache-2.0): profile and view shapes, ontology modules, examples, test fixtures.
 * Both pinned by commit. Upstream paths with spaces ("SHACL Shapes/", "battery ontology.ttl") are
 * written with dashes, because a validator configuration lists files comma-separated; MANIFEST.json
 * records the upstream path of every file.
 *
 * Extensions/upstream/cirpass2-textile still mirrors 1.1.2 for the vocabulary and the crosswalk;
 * this sync only feeds the hosted validation types.
 */
import { createHash } from "node:crypto";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");

interface Release {
  out: string;
  title: string;
  version: string;
  repository: string;
  commit: string;
  license: string;
  status?: string;
  /** Upstream path prefix and the paths (relative to it) to take: exact files or `dir/*.ext`. */
  base: string;
  take: string[];
}

const RELEASES: Release[] = [
  {
    out: "vendor/cirpass2-textile/2.0.0",
    title: "CIRPASS-2 Textile ontology, publication package",
    version: "2.0.0",
    repository: "https://github.com/CIRPASS-2/ontologies-docs",
    commit: "ff8a429",
    license: "https://creativecommons.org/licenses/by/4.0/",
    base: "Textile/2.0.0/package/",
    take: ["shacl/*.ttl", "ontology/*.ttl", "mireot/*.ttl", "examples/*.ttl", "tests/abox_corpus/expectations/shacl-expectations.json", "tests/abox_corpus/fixtures/valid/*.ttl", "tests/abox_corpus/fixtures/invalid/*.ttl", "LICENSE.md", "VERSION"],
  },
  {
    out: "vendor/cirpass2-battery/0.3.0",
    title: "CIRPASS-2 Battery shapes (ontology 0.4.0)",
    version: "0.3.0",
    status: "draft",
    repository: "https://github.com/CIRPASS-2/ontologies-battery",
    commit: "c8e5847",
    license: "https://www.apache.org/licenses/LICENSE-2.0",
    base: "",
    take: ["SHACL Shapes/*.ttl", "Ontology/*.ttl", "Examples/*.ttl", "tests/fixtures/*.jsonld", "LICENSE.txt"],
  },
];

const dashed = (p: string) => p.replace(/ /g, "-");

for (const r of RELEASES) {
  const repo = r.repository.replace("https://github.com/", "");
  const commit = ((await (await fetch(`https://api.github.com/repos/${repo}/commits/${r.commit}`)).json()) as { sha: string }).sha;
  const tree = ((await (await fetch(`https://api.github.com/repos/${repo}/git/trees/${commit}?recursive=1`)).json()) as { tree: { path: string; type: string }[] }).tree;
  const wanted = tree.filter((e) => e.type === "blob" && e.path.startsWith(r.base)).map((e) => e.path.slice(r.base.length)).filter((p) =>
    r.take.some((t) => (t.includes("*") ? p.startsWith(t.slice(0, t.indexOf("*"))) && !p.slice(t.indexOf("*")).includes("/") && p.endsWith(t.slice(t.indexOf("*") + 1)) : p === t)),
  );
  const files: { path: string; upstream: string; sha256: string }[] = [];
  for (const p of wanted.sort()) {
    const res = await fetch(`https://raw.githubusercontent.com/${repo}/${commit}/${encodeURI(r.base + p)}`);
    if (!res.ok) throw new Error(`${r.base}${p}: HTTP ${res.status}`);
    const bytes = Buffer.from(await res.arrayBuffer());
    const local = dashed(p);
    mkdirSync(dirname(join(ROOT, r.out, local)), { recursive: true });
    writeFileSync(join(ROOT, r.out, local), bytes);
    files.push({ path: local, upstream: r.base + p, sha256: createHash("sha256").update(bytes).digest("hex") });
  }
  writeFileSync(join(ROOT, r.out, "MANIFEST.json"), JSON.stringify({
    $comment: "GENERATED by scripts/sync-cirpass2-shapes.ts - do not edit.",
    title: r.title,
    version: r.version,
    ...(r.status ? { status: r.status } : {}),
    commit,
    retrieved: new Date().toISOString().slice(0, 10),
    repository: r.repository,
    license: r.license,
    files: files.sort((a, b) => a.path.localeCompare(b.path)),
  }, null, 2) + "\n");
  console.log(`${r.out}: ${files.length} files (${repo}@${commit.slice(0, 8)})`);
}
