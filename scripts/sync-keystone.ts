/**
 * Sync the published DPP Keystone v3 validation artifacts into vendor/dpp-keystone/v3/.
 *
 *   pnpm run sync:keystone
 *
 * NETWORK SYNC — NEVER RUN THIS AS PART OF A BULK REGENERATION. Sync on purpose, in its own
 * commit, and read the diff (see the note in sync-cirpass2.ts).
 *
 * SOURCE. DPP Keystone (github.com/dpp-keystone-org/DPPKeystoneOrg, CC0 1.0) publishes its v3
 * specification on dpp-keystone.org/spec/: JSON Schemas (a core document schema plus conditional
 * sector schemas, keyed on contentSpecificationIds), SHACL shapes generated from the ontology (JSON-
 * LD), the ontology, the JSON-LD contexts and example passports. The repository holds the sources
 * with a {{VERSION}} placeholder and no SHACL; the site holds what the build makes of them, which is
 * what a Keystone document is checked with, so the published files are vendored. The release is
 * pinned by the repository commit current at the sync and by the SHA-256 of every file.
 *
 * OUTPUT.
 *   vendor/dpp-keystone/v3/<path under /spec/>   verbatim
 *   vendor/dpp-keystone/v3/MANIFEST.json         commit, retrieval date, licence, per-file SHA-256
 */
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SITE = "https://dpp-keystone.org/spec/";
const REPOSITORY = "https://github.com/dpp-keystone-org/DPPKeystoneOrg";
const VERSION = "v3";

const CORE = ["Compliance", "DoPC", "EPD", "EPDIndicators", "EPDLifecycle", "EPDMetadata", "Header", "MTC", "Organization", "Product", "RelatedResource", "Signature", "Unit"];
const SECTORS = ["Battery", "Construction", "Electronics", "EUApparelSizeSystem", "IronSteel", "Textile"];
const SECTOR_SCHEMAS = ["battery", "battery-ev", "battery-industrial", "battery-lmv", "construction", "electronics", "iron-steel", "textile"];
const SHARED_SCHEMAS = ["certification", "component", "dopc", "epd", "general-product", "mtc", "organization", "packaging", "postal-address", "product-characteristic", "related-resource"];
const CONTEXTS = ["battery", "construction", "core", "dopc", "ec-to-keystone", "electronics", "epd", "general-product", "iron-steel", "keystone-to-ec", "mtc", "packaging", "textile"];
const EXAMPLES = [
  "battery-dpp-ec-aligned-v1", "battery-dpp-v1", "battery-industrial-dpp-v1", "battery-lmv-dpp-v1", "construction-product-dpp-v1",
  "drill-dpp-v1-private", "drill-dpp-v1", "iron-steel-dpp-v1", "rail-dpp-v1", "sock-dpp-v2",
];

const files = [
  `validation/${VERSION}/json-schema/dpp.schema.json`,
  ...SECTOR_SCHEMAS.map((s) => `validation/${VERSION}/json-schema/sector/${s}.schema.json`),
  ...SHARED_SCHEMAS.map((s) => `validation/${VERSION}/json-schema/shared/${s}.schema.json`),
  ...CORE.map((c) => `validation/${VERSION}/shacl/core/${c}-shapes.shacl.jsonld`),
  ...SECTORS.map((s) => `validation/${VERSION}/shacl/sectors/${s}-shapes.shacl.jsonld`),
  `ontology/${VERSION}/dpp-ontology.jsonld`,
  ...CONTEXTS.map((c) => `contexts/${VERSION}/dpp-${c}.context.jsonld`),
  ...EXAMPLES.map((e) => `examples/${e}.json`),
];

const commit = execFileSync("git", ["ls-remote", REPOSITORY, "HEAD"], { encoding: "utf8" }).split(/\s/)[0];
const out = join(ROOT, "vendor/dpp-keystone", VERSION);
const manifest: { path: string; sha256: string }[] = [];
for (const path of files) {
  const res = await fetch(SITE + path);
  if (!res.ok) throw new Error(`${path}: HTTP ${res.status}`);
  const bytes = Buffer.from(await res.arrayBuffer());
  JSON.parse(bytes.toString("utf8"));
  mkdirSync(dirname(join(out, path)), { recursive: true });
  writeFileSync(join(out, path), bytes);
  manifest.push({ path, sha256: createHash("sha256").update(bytes).digest("hex") });
}
writeFileSync(join(out, "MANIFEST.json"), JSON.stringify({
  $comment: "GENERATED by scripts/sync-keystone.ts - do not edit.",
  title: "DPP Keystone specification, validation artifacts",
  version: VERSION,
  commit,
  retrieved: new Date().toISOString().slice(0, 10),
  repository: REPOSITORY,
  source: SITE,
  license: "https://creativecommons.org/publicdomain/zero/1.0/",
  files: manifest.sort((a, b) => a.path.localeCompare(b.path)),
}, null, 2) + "\n");
console.log(`vendor/dpp-keystone/${VERSION}: ${manifest.length} files (repository HEAD ${commit.slice(0, 8)})`);
