/**
 * Sync the BatteryPass-Ready data model (JSON Schemas) into vendor/batterypass-ready/<version>/.
 *
 *   pnpm run sync:batterypass-ready
 *
 * NETWORK SYNC — NEVER RUN THIS AS PART OF A BULK REGENERATION. Sync on purpose, in its own
 * commit, and read the diff (see the note in sync-cirpass2.ts).
 *
 * SOURCE. The BatteryPass-Ready consortium publishes its data model as JSON Schema (and XSD) per
 * battery category in git.gefeg.com/bp/BatteryPassDataModel. The files are read at a pinned commit,
 * so the same sync always yields the same bytes. Each category comes twice: `<Category>_2.0.1.json`
 * (all requirements) and `<Category>_Feb27_2.0.1.json` (the requirements from February 2027).
 *
 * OUTPUT.
 *   vendor/batterypass-ready/<version>/JSONSchemaFiles/*.json   verbatim
 *   vendor/batterypass-ready/<version>/changelog.md              verbatim (v1.3 → v2.0)
 *   vendor/batterypass-ready/<version>/MANIFEST.json             commit, licence, per-file SHA-256
 *
 * Licence: CC BY 4.0, © BatteryPass-Ready Consortium (repository README).
 */
import { createHash } from "node:crypto";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");

/** The pinned release. Bump deliberately, in the sync commit. */
const RELEASE = {
  version: "2.0.1",
  commit: "64761a79bc287f2e0eb371837c1d02e4eacb9c37",
  committed: "2026-09-23",
  repository: "https://git.gefeg.com/bp/BatteryPassDataModel",
  license: "https://creativecommons.org/licenses/by/4.0/",
};
const CATEGORIES = ["EV", "LMT", "Industrial_Without_BMS", "Other_Industrial_Above_2kWh", "Stationary_Industrial_Above_2kWh"];

const raw = (path: string) => `${RELEASE.repository}/-/raw/${RELEASE.commit}/${path}`;
const files: [string, string][] = [
  ...CATEGORIES.flatMap((c) => ["", "_Feb27"].map((v): [string, string] => {
    const name = `${c}${v}_${RELEASE.version}.json`;
    return [`JSONSchemaFiles/${name}`, `JSONSchemaFiles/v${RELEASE.version}/${name}`];
  })),
  ["changelog.md", "AdditionalDocuments/Changelog/changelog.md"],
];

const out = join(ROOT, "vendor/batterypass-ready", RELEASE.version);
const manifest: { path: string; sha256: string }[] = [];
for (const [local, remote] of files) {
  const res = await fetch(raw(remote));
  if (!res.ok) throw new Error(`${remote}: HTTP ${res.status}`);
  const bytes = Buffer.from(await res.arrayBuffer());
  if (local.endsWith(".json")) JSON.parse(bytes.toString("utf8"));
  mkdirSync(dirname(join(out, local)), { recursive: true });
  writeFileSync(join(out, local), bytes);
  manifest.push({ path: local, sha256: createHash("sha256").update(bytes).digest("hex") });
}
writeFileSync(join(out, "MANIFEST.json"), JSON.stringify({
  $comment: "GENERATED by scripts/sync-batterypass-ready.ts - do not edit.",
  title: "BatteryPass-Ready data model, JSON Schemas",
  ...RELEASE,
  files: manifest.sort((a, b) => a.path.localeCompare(b.path)),
}, null, 2) + "\n");
console.log(`vendor/batterypass-ready/${RELEASE.version}: ${manifest.length} files`);
