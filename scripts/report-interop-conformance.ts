#!/usr/bin/env tsx
/**
 * The conformance statement of this release towards the external DPP models it bridges.
 *
 * For every validation target (extensions/common/interop/targets/<target>/<version>/target.json,
 * scripts/lib/targets.ts) it records:
 *   - the release checked against: publisher, version, pin (commit or archive hash), source,
 *     licence, and that every bundled artifact matches the vendor manifest's SHA-256;
 *   - the GITB validation types hosted for it (SHACL and/or JSON) with the artifacts behind each;
 *   - every fixture's verdict per type: the publisher's own examples (they test the artifacts and
 *     our hosting of them) and the documents our crosswalk lifts (they test us);
 *   - the deviations a defect of the release makes unavoidable, each with its reason and the
 *     findings it covers.
 *
 * What is claimed, per target: our crosswalk output has the target's form (no finding other than a
 * missing value or an accepted deviation). A missing value is data the source example does not
 * state, listed but not a failure of the mapping.
 *
 * Output (generated, do not edit): docs/conformance/INTEROP_CONFORMANCE.md and .json. Without
 * --write the committed files are compared and the run fails on drift, on a publisher example the
 * hosted types reject, on a wrong form in our output, and on an accepted deviation no document
 * needs any more, so the statement cannot go stale. Run it after every change to a target, its
 * artifacts, a crosswalk profile or the package version.
 *
 * Usage:
 *   tsx scripts/report-interop-conformance.ts [--write]
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";
import { ROOT } from "./lib/modules.ts";
import { fixturesOf, loadTargets, provenance, verdict, verifyArtifacts, type Verdict } from "./lib/targets.ts";

const WRITE = process.argv.includes("--write");
const OUT_DIR = "docs/conformance";
const MD = join(OUT_DIR, "INTEROP_CONFORMANCE.md");
const JSON_OUT = join(OUT_DIR, "INTEROP_CONFORMANCE.json");

interface Row {
  file: string;
  role: "publisher" | "openepcis" | "roundtrip";
  type: string;
  verdict: "valid" | "conforms" | "incomplete" | "wrong form";
  missing: string[];
  form: string[];
  accepted: string[];
}

const label = (v: Verdict): Row["verdict"] =>
  v.form.length ? "wrong form" : v.missing.length ? "incomplete" : v.valid ? "valid" : "conforms";

async function main() {
  const version = JSON.parse(readFileSync(join(ROOT, "package.json"), "utf8")).version as string;
  const problems: string[] = [];
  const report: Record<string, unknown>[] = [];
  const md: string[] = [
    `# Conformance to external DPP models`,
    ``,
    `<!-- GENERATED by scripts/report-interop-conformance.ts (pnpm run build:interop-conformance) — do not edit. -->`,
    ``,
    `OpenEPCIS DPP-Ready **${version}**. For every external model this release bridges, the release`,
    `of that model it was checked against, the GITB validation types hosted for it, and the verdict on`,
    `each document: the publisher's own examples, and what our crosswalk produces.`,
    ``,
    `- **valid**: no finding at all; what the hosted validation type answers.`,
    `- **conforms**: valid apart from an accepted deviation (a defect of the release, reason below).`,
    `- **incomplete**: the right form, but values the target requires are absent. For our output`,
    `  (from \`openepcis\`) these are values the source passport does not state; for a round trip (the`,
    `  publisher's document taken in and lifted back) they are losses of our crosswalk, listed per term`,
    `  in the profile's \`conformance.txt\` and \`roundtrip.txt\`.`,
    `- **wrong form**: a finding other than a missing value. Never accepted for our output.`,
    ``,
    `Types are hosted on the OpenEPCIS DPP-Ready validator (SHACL: EU Interoperability Test Bed,`,
    `domain \`openepcis\`; JSON: self-hosted, \`gitb/docker/docker-compose.validators.yml\`). The`,
    `publisher's artifacts are bundled byte for byte; OpenEPCIS adds one presence shape per SHACL type`,
    `(the document must contain the root class), nothing else. Hosting does not imply endorsement by`,
    `the publisher.`,
    ``,
  ];

  const summary: string[] = [
    `| Target | Release | Pin | Types | Publisher examples valid | Our output in form | Our output complete | Round trips complete |`,
    `|---|---|---|---|---|---|---|---|`,
  ];
  const sections: string[] = [];

  for (const t of loadTargets()) {
    const m = t.manifestData;
    const bad = verifyArtifacts(t);
    problems.push(...bad.map((b) => `${t.id} ${t.version}: ${b}`));
    const rows: Row[] = [];
    const used = new Map<string, Set<string>>();
    for (const f of fixturesOf(t)) {
      if (!f.types.length) problems.push(`${t.id} ${t.version}: fixture ${f.file} belongs to no type`);
      const doc = JSON.parse(readFileSync(join(ROOT, f.file), "utf8"));
      for (const id of f.types) {
        const v = await verdict(t, t.types.find((x) => x.id === id)!, doc, { noShacl: !!f.noShacl });
        for (const a of v.accepted) {
          const reason = t.accepted.find((x) => x.reason === a.reason)!.match;
          if (!used.has(reason)) used.set(reason, new Set());
          used.get(reason)!.add(a.finding);
        }
        rows.push({ file: f.file, role: f.role, type: id, verdict: label(v), missing: v.missing, form: v.form, accepted: v.accepted.map((a) => a.finding) });
        if (f.role === "publisher" && !v.valid) problems.push(`${id}: the publisher's example ${f.file} is not valid`);
        if (f.role !== "publisher" && v.form.length) problems.push(`${id}: our ${f.file} has the wrong form: ${v.form[0]}`);
      }
    }
    for (const a of t.accepted) if (!used.has(a.match)) problems.push(`${t.id} ${t.version}: accepted deviation /${a.match}/ is needed by no document any more`);

    const pub = rows.filter((r) => r.role === "publisher");
    const ours = rows.filter((r) => r.role === "openepcis");
    const trips = rows.filter((r) => r.role === "roundtrip");
    const pin = m.commit ?? (m.archiveSha256 ? `sha256:${m.archiveSha256}` : "");
    summary.push(
      `| ${t.title} | ${t.version} | \`${pin.slice(0, 19)}\` | ${t.types.length} | ${pub.filter((r) => r.verdict === "valid").length}/${pub.length} | ` +
        `${[...ours, ...trips].filter((r) => r.verdict !== "wrong form").length}/${ours.length + trips.length} | ` +
        `${ours.filter((r) => r.verdict === "valid" || r.verdict === "conforms").length}/${ours.length} | ` +
        `${trips.filter((r) => r.verdict === "valid" || r.verdict === "conforms").length}/${trips.length} |`,
    );

    const sec: string[] = [
      `## ${t.title} ${t.version}`,
      ``,
      `| | |`,
      `|---|---|`,
      `| Publisher | ${t.publisher} |`,
      `| Release | ${t.version} |`,
      `| Pin | \`${pin}\` |`,
      `| Source | ${m.repository ?? m.source ?? ""} |`,
      `| Licence | ${m.license} |`,
      `| Artifacts | ${t.manifest} (${m.files.length} files, SHA-256 ${bad.length ? `**${bad.length} mismatch(es)**` : "verified"}) |`,
      `| Registry | ${t.dir}/target.json |`,
      `| Crosswalk profile | extensions/common/interop/crosswalk/${t.profile} |`,
      ``,
      `### Validation types`,
      ``,
      `| Type | Checks | Artifacts |`,
      `|---|---|---|`,
      ...t.types.map((ty) => `| \`${ty.id}\` | ${[ty.shapes.length && "SHACL", ty.schemas.length && "JSON Schema"].filter(Boolean).join(" + ")} | ${[...ty.shapes, ...ty.schemas].map((f) => `\`${f.replace(/.*\//, "")}\``).join(", ")} |`),
      ``,
      `### Documents`,
      ``,
      `| Document | From | Type | Verdict | Missing | Accepted |`,
      `|---|---|---|---|---|---|`,
      ...rows.map((r) => `| \`${r.file.replace(/^(vendor|extensions\/common\/interop\/crosswalk|extensions\/eu\/battery\/examples)\//, "")}\` | ${r.role} | \`${r.type.replace(`x.${t.id}-${t.version}.`, "")}\` | ${r.verdict} | ${r.missing.length || ""} | ${r.accepted.length || ""} |`),
      ``,
    ];
    if (t.exclude?.length) {
      sec.push(`### Publisher examples left out`, ``);
      for (const x of t.exclude) sec.push(`- \`${x.file.replace(/.*\//, "")}\`${x.only ? ` (from the ${x.only.toUpperCase()} check only)` : ""}: ${x.reason}`);
      sec.push(``);
    }
    if (t.accepted.length) {
      sec.push(`### Accepted deviations`, ``);
      for (const a of t.accepted) sec.push(`- \`/${a.match}/\`: ${a.reason} (${used.get(a.match)?.size ?? 0} finding(s))`);
      sec.push(``);
    }
    sections.push(...sec);
    report.push({
      target: t.id,
      version: t.version,
      title: t.title,
      publisher: t.publisher,
      pin,
      source: m.repository ?? m.source,
      license: m.license,
      provenance: provenance(t),
      artifactsVerified: !bad.length,
      types: t.types.map((ty) => ({ id: ty.id, label: ty.label, shapes: ty.shapes, schemas: ty.schemas })),
      documents: rows,
      accepted: t.accepted.map((a) => ({ ...a, findings: [...(used.get(a.match) ?? [])].sort() })),
    });
  }

  md.push(...summary, ``, ...sections);
  const files = new Map([
    [MD, md.join("\n")],
    [JSON_OUT, JSON.stringify({ $comment: "GENERATED by scripts/report-interop-conformance.ts - do not edit.", release: version, targets: report }, null, 2) + "\n"],
  ]);

  const drift: string[] = [];
  for (const [rel, content] of files) {
    let existing: string | undefined;
    try {
      existing = readFileSync(join(ROOT, rel), "utf8");
    } catch {
      /* new */
    }
    if (existing === content) continue;
    drift.push(rel);
    if (WRITE) {
      mkdirSync(join(ROOT, OUT_DIR), { recursive: true });
      writeFileSync(join(ROOT, rel), content);
    }
  }

  console.log(summary.join("\n"));
  if (problems.length) {
    console.log(`\n✗ interop conformance:`);
    for (const p of problems) console.log(`    ${p}`);
  }
  if (drift.length && !WRITE) {
    console.log(`\n✗ the committed conformance statement has drifted: ${drift.join(", ")}`);
    console.log(`Regenerate with: pnpm run build:interop-conformance`);
  } else if (drift.length) {
    console.log(`\n✓ wrote ${drift.join(", ")}`);
  }
  if (problems.length || (drift.length && !WRITE)) process.exit(1);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
